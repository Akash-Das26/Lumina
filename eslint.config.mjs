// ESLint flat config (ESLint 9/10) for the whole workspace.
//
// Scope: the JavaScript/TypeScript sources in `artifacts/`, `lib/` and
// `scripts/`. Vendored/generated output is ignored (the orval-generated API
// clients and zod schemas are machine-written, and `dist/` is build output).
//
// Deliberately minimal and non-type-aware: no `project` service, so linting
// stays fast enough to run on every PR and does not need a build first.
import js from "@eslint/js";
import globals from "globals";
import reactHooks from "eslint-plugin-react-hooks";
import tseslint from "typescript-eslint";

export default tseslint.config(
  {
    ignores: [
      "**/node_modules/**",
      "**/dist/**",
      "**/.agents/**",
      "**/coverage/**",
      // Machine-generated orval clients (regenerated by `pnpm codegen`).
      "lib/api-client-react/src/generated/**",
      "lib/api-zod/src/generated/**",
      // Browser-harness bundles/files served as-is.
      "scripts/browser/index.html",
    ],
  },

  // Every JS/TS file: the ESLint recommended set plus TypeScript syntax.
  {
    files: ["**/*.{js,mjs,cjs,ts,mts,cts,tsx}"],
    extends: [js.configs.recommended, ...tseslint.configs.recommended],
    languageOptions: {
      ecmaVersion: 2023,
      sourceType: "module",
    },
    rules: {
      // The API deliberately logs/propagates `unknown` errors and rejects
      // anything it cannot classify, so unused catch bindings and forgiving
      // `any` at type boundaries are intentional in this codebase.
      "@typescript-eslint/no-explicit-any": "warn",
      // `_`-prefixed names are the established convention for unused
      // parameters (mock signatures, interface compatibility).
      "@typescript-eslint/no-unused-vars": [
        "error",
        {
          argsIgnorePattern: "^_",
          varsIgnorePattern: "^_",
          caughtErrorsIgnorePattern: "^_",
          ignoreRestSiblings: true,
        },
      ],
    },
  },

  // Node-side code: the API server, workspace libraries and scripts.
  {
    files: [
      "artifacts/api-server/**/*.ts",
      "lib/**/*.ts",
      "scripts/**/*.{js,mjs,ts}",
    ],
    languageOptions: { globals: { ...globals.node } },
  },

  // Browser-side code: the React app.
  {
    files: ["artifacts/lumina/**/*.{ts,tsx}"],
    languageOptions: {
      globals: { ...globals.browser },
      parserOptions: { ecmaFeatures: { jsx: true } },
    },
    plugins: { "react-hooks": reactHooks },
    rules: {
      // The canonical hooks rules. The plugin's newer React-Compiler rules
      // (purity, immutability, set-state-in-effect, …) are not enabled: they
      // flag patterns this codebase uses deliberately (e.g. syncing local chat
      // state with a refetched conversation) and turning them on would mean a
      // broad rewrite rather than a lint baseline. See docs/review.md.
      "react-hooks/rules-of-hooks": "error",
      "react-hooks/exhaustive-deps": "warn",
    },
  },

  // Test files run in Node (vitest) with jsdom globals where the environment
  // comment says so; they legitimately use dynamic imports and loose mocks.
  {
    files: ["**/test/**/*.{ts,tsx}", "**/*.spec.{ts,tsx}"],
    languageOptions: {
      globals: { ...globals.node, ...globals.browser, ...globals.vitest },
    },
    rules: {
      "@typescript-eslint/no-explicit-any": "off",
    },
  },

  // Build/config scripts at the repo root.
  {
    files: ["*.{js,mjs,cjs,ts}"],
    languageOptions: { globals: { ...globals.node } },
  },
);
